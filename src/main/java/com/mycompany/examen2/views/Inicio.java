    // Método para llenar el JTable con los datos de SQLite
    private void cargarTabla() {
        // Limpiamos la tabla primero
        DefaultTableModel modelo = (DefaultTableModel) jt_frases.getModel();
        modelo.setRowCount(0);

        // Obtenemos los datos de SQLite
        FraseEncriptadaDAO dao = new FraseEncriptadaDAO();
        java.util.List<com.mycompany.examen2.model.FraseEncriptada> lista = dao.obtenerFrases();

        // Llenamos la tabla fila por fila
        for (FraseEncriptada f : lista) {
            // Mostramos el texto encriptado y el tamaño del archivo de configuración (solo como referencia)
            modelo.addRow(new Object[]{
                f.getFrase(),
                "Config guardada (" + f.getConfig().length + " bytes)"
            });
        }
    }

