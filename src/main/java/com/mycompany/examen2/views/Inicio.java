    private void jb_elimiar_registroMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jb_elimiar_registroMouseClicked
        // 1. Verificar que el usuario haya seleccionado una fila en la tabla
        int filaSeleccionada = jt_frases.getSelectedRow();

        if (filaSeleccionada == -1) {
            JOptionPane.showMessageDialog(this,
                    "Por favor, selecciona un registro de la tabla para eliminar.",
                    "Advertencia", JOptionPane.WARNING_MESSAGE);
            return;
        }

        // 2. Pedir confirmación al usuario antes de eliminar (Buena práctica)
        int confirmacion = JOptionPane.showConfirmDialog(this,
                "¿Estás seguro de que deseas eliminar este registro de la base de datos?",
                "Confirmar Eliminación",
                JOptionPane.YES_NO_OPTION,
                JOptionPane.QUESTION_MESSAGE);

        // Si el usuario presiona "Sí" (YES_OPTION)
        if (confirmacion == JOptionPane.YES_OPTION) {
            try {
                // 3. Obtener la lista para saber qué objeto seleccionó
                FraseEncriptadaDAO dao = new FraseEncriptadaDAO();
                java.util.List<FraseEncriptada> lista = dao.obtenerFrases();

                // Obtenemos la frase usando el índice de la fila seleccionada
                FraseEncriptada fraseAEliminar = lista.get(filaSeleccionada);

                // 4. Llamamos al método eliminar del DAO
                if (dao.eliminarFrase(fraseAEliminar)) {
                    JOptionPane.showMessageDialog(this,
                            "Registro eliminado con éxito.",
                            "Éxito", JOptionPane.INFORMATION_MESSAGE);

                    // 5. Actualizamos la tabla para que desaparezca la fila borrada
                    cargarTabla();

                    // Limpiamos el campo de texto por si tenía algo escrito
                    jtf_frase.setText("");
                } else {
                    JOptionPane.showMessageDialog(this,
                            "No se pudo eliminar el registro en la base de datos.",
                            "Error de BD", JOptionPane.ERROR_MESSAGE);
                }

            } catch (Exception ex) {
                JOptionPane.showMessageDialog(this,
                        "Ocurrió un error al intentar eliminar: " + ex.getMessage(),
                        "Error", JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_jb_elimiar_registroMouseClicked

    private void jt_frasesMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jt_frasesMouseClicked
        // 1. Obtener el índice de la fila a la que el usuario le hizo clic
        int filaSeleccionada = jt_frases.getSelectedRow();

        // 2. Verificar que la selección sea válida (no sea -1)
        if (filaSeleccionada != -1) {

            // 3. Obtener el valor de la columna 0 (que es donde está la "Frase Encriptada")
            // Usamos getValueAt(fila, columna)
            String textoSeleccionado = jt_frases.getValueAt(filaSeleccionada, 0).toString();

            // 4. Colocar ese texto en tu campo de texto jtf_frase
            jtf_frase.setText(textoSeleccionado);
        }
    }//GEN-LAST:event_jt_frasesMouseClicked

